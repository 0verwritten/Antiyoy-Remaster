// Packs the hand-drawn "remaster" building sprites into a slim atlas the web
// renderer can draw, mirroring gen-sprites.mjs. Source PNGs live in
// assets/buildings/source/ (500x500 with transparent padding). Each is
// auto-trimmed to its opaque bounding box, then fit (contain) and centered
// into a square frame so render.ts can draw it centered on a hex like the
// original sprites.
//
// The atlas is written to assets/web/buildings.png and served from jsDelivr
// (same as atlas.png) so the image bytes stay out of the client bundle.
// Usage: node devtools/gen-buildings.mjs
import { chromium } from "playwright-core";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "assets/buildings/source");
const spritesPath = join(root, "web/client/sprites.ts");
const atlasOut = join(root, "assets/web/buildings.png");

// name -> source file. Names are referenced from render.ts.
const SOURCES = {
  town_house: "house.png", // province capital, slay mode
  town_castle: "castle.png", // province capital, default mode
  tower_day: "watchtower.png", // weak defense tower (day)
  strong_tower_day: "fortress.png", // strong defense tower (day)
  tower_night: "lamp.png", // weak tower fixture (Night Battle)
  strong_tower_night: "lamp_ornate.png", // strong tower fixture (Night Battle)
};

const FRAME = 128; // square frame each sprite is fit into
const GUTTER = 1; // guard against sampling bleed
const COLS = 3;
const ALPHA = 16; // opacity threshold for trimming

const names = Object.keys(SOURCES);
const rows = Math.ceil(names.length / COLS);
const outW = COLS * (FRAME + GUTTER) - GUTTER;
const outH = rows * (FRAME + GUTTER) - GUTTER;

const inputs = names.map((name, i) => ({
  name,
  dataUrl: "data:image/png;base64," +
    readFileSync(join(srcDir, SOURCES[name])).toString("base64"),
  fx: (i % COLS) * (FRAME + GUTTER),
  fy: Math.floor(i / COLS) * (FRAME + GUTTER),
}));

const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage();
const dataUrl = await page.evaluate(
  async ({ inputs, outW, outH, FRAME, ALPHA }) => {
    const out = document.createElement("canvas");
    out.width = outW;
    out.height = outH;
    const octx = out.getContext("2d");

    for (const inp of inputs) {
      const img = new Image();
      await new Promise((res, rej) => {
        img.onload = res;
        img.onerror = rej;
        img.src = inp.dataUrl;
      });
      // Draw to a scratch canvas to read pixels and find the opaque bbox.
      const sc = document.createElement("canvas");
      sc.width = img.width;
      sc.height = img.height;
      const sctx = sc.getContext("2d");
      sctx.drawImage(img, 0, 0);
      const { data } = sctx.getImageData(0, 0, img.width, img.height);
      let minX = img.width, minY = img.height, maxX = -1, maxY = -1;
      for (let y = 0; y < img.height; y++) {
        for (let x = 0; x < img.width; x++) {
          if (data[(y * img.width + x) * 4 + 3] > ALPHA) {
            if (x < minX) minX = x;
            if (x > maxX) maxX = x;
            if (y < minY) minY = y;
            if (y > maxY) maxY = y;
          }
        }
      }
      if (maxX < 0) continue; // fully transparent
      const bw = maxX - minX + 1;
      const bh = maxY - minY + 1;
      // Contain within the frame, preserving aspect ratio, centered.
      const scale = FRAME / Math.max(bw, bh);
      const dw = bw * scale;
      const dh = bh * scale;
      const dx = inp.fx + (FRAME - dw) / 2;
      const dy = inp.fy + (FRAME - dh) / 2;
      octx.imageSmoothingEnabled = true;
      octx.imageSmoothingQuality = "high";
      octx.drawImage(img, minX, minY, bw, bh, dx, dy, dw, dh);
    }
    return out.toDataURL("image/png");
  },
  { inputs, outW, outH, FRAME, ALPHA }
);
await browser.close();

writeFileSync(atlasOut, Buffer.from(dataUrl.replace(/^data:image\/png;base64,/, ""), "base64"));

// Patch the BUILDINGS block in sprites.ts in place (between the markers).
const rectLines = inputs
  .map((p) => `  ${p.name}: { x: ${p.fx}, y: ${p.fy}, w: ${FRAME}, h: ${FRAME} },`)
  .join("\n");
const src = readFileSync(spritesPath, "utf8");
const begin = "// >>> BUILDINGS (generated by devtools/gen-buildings.mjs) >>>";
const end = "// <<< BUILDINGS <<<";
const b = src.indexOf(begin);
const e = src.indexOf(end);
if (b < 0 || e < 0) throw new Error("BUILDINGS markers not found in sprites.ts");
const replaced =
  src.slice(0, b + begin.length) +
  `\nexport const BUILDINGS: Record<string, SpriteRect> = {\n${rectLines}\n};\n` +
  src.slice(e);
writeFileSync(spritesPath, replaced);

console.log(`Wrote ${atlasOut} (${outW}x${outH}) and patched ${spritesPath}`);
